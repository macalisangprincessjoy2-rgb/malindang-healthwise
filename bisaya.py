def bisaya_text(value):
    """Translate known application labels while preserving proper names."""
    if value is None:
        return ''
    text = str(value)
    translated = BISAYA_TEXT.get(text)
    if translated is not None:
        return translated
    suffix = ' Barangay Health Station'
    if text.endswith(suffix):
        barangay = text[:-len(suffix)]
        return f'Istasyon sa Panglawas sa Barangay {barangay}'
    return text
